function tracking(status: ShipmentStatus, country: string, createdAt: string) {
  const completed = { pending: 1, printed: 2, transit: 3, delivered: 6, exception: 3, returned: 4 }[status];
  const nodes: [string, string, string][] = [
    ['订单创建', '深圳分拣中心', createdAt],
    ['已打单 · 面单生成', '物流渠道', '2026-06-30 10:05'],
    ['干线运输 · 已揽收', '跨境干线', '2026-07-01 02:18'],
    ['目的国清关完成', country, '2026-07-02 14:40'],
    ['尾程派送中', `${country} · 本地派送`, '2026-07-03 09:22'],
    ['已签收', '收件人已签收', '2026-07-03 16:08'],
  ];
  return nodes.map(([title, place, occurredAt], index) => ({
    id: `track-${index}`,
    title,
    place,
    occurredAt,
    completed: index < completed,
    current: index === completed - 1,
  }));
}

